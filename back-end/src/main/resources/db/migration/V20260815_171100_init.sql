(
    ref_planning_id    BIGINT GENERATED ALWAYS AS IDENTITY,
    ref_timeline_id    BIGINT       NOT NULL,
    week_type          VARCHAR(50)  NOT NULL,
    day_of_week        INTEGER      NOT NULL,
    exercice_order     INTEGER      NOT NULL,
    categorie_exercice VARCHAR(100) NOT NULL,
    type_exercice      VARCHAR(100),
    strength_weakness  VARCHAR(10),
    set_number         INTEGER,
    rep_number         INTEGER,
    rep_label          VARCHAR(20),
    CONSTRAINT pk_ref_plannings PRIMARY KEY (ref_planning_id),
    CONSTRAINT chk_ref_plannings_1 CHECK (day_of_week BETWEEN 1 AND 5),
    CONSTRAINT chk_ref_plannings_2 CHECK (exercice_order > 0),
    CONSTRAINT chk_ref_plannings_3 CHECK (set_number > 0),
    CONSTRAINT chk_ref_plannings_4 CHECK (rep_number > 0),
    CONSTRAINT chk_ref_plannings_5 CHECK (strength_weakness IN ('STRENGTH', 'WEAKNESS', NULL)),
    CONSTRAINT fk_ref_plannings_1 FOREIGN KEY (ref_timeline_id) REFERENCES ref_timelines (ref_timeline_id)
);

COMMENT ON TABLE ref_plannings IS 'Planning de référence associé à une timeline';
