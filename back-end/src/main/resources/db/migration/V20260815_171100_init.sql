COMMENT ON COLUMN eval_summaries.endurance IS 'Profil endurance : LOW, MID, HIGH';
COMMENT ON COLUMN eval_summaries.squat IS 'Profil squat : STRENGTH, MID, SPEED';
COMMENT ON COLUMN eval_summaries.pull IS 'Profil tirage : STRENGTH, MID, SPEED';
COMMENT ON COLUMN eval_summaries.snatch_strength IS 'Point fort à l''arraché';
COMMENT ON COLUMN eval_summaries.snatch_weakness IS 'Point faible à l''arraché';
COMMENT ON COLUMN eval_summaries.clean_strength IS 'Point fort à l''épaulé';
COMMENT ON COLUMN eval_summaries.clean_weakness IS 'Point faible à l''épaulé';
