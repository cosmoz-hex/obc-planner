-- ------------------------------------------------------------
-- PROG
-- Programme d entraînement généré à partir d une évaluation
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS programmes
(
    programme_id  INTEGER GENERATED BY DEFAULT AS IDENTITY,
    evaluation_id INTEGER NOT NULL,
    weeks         INTEGER NOT NULL,
    frequency     INTEGER NOT NULL,
    duration      INTEGER,
    start_date    DATE NOT NULL,
    end_date      DATE NOT NULL,
    snatch_goal   INTEGER,
    cj_goal       INTEGER,
    CONSTRAINT pk_programmes PRIMARY KEY (programme_id),
    CONSTRAINT chk_programmes_1 CHECK (weeks > 0),
    CONSTRAINT chk_programmes_2 CHECK (frequency BETWEEN 3 AND 5),
    CONSTRAINT chk_programmes_3 CHECK (duration BETWEEN 90 AND 150),
    CONSTRAINT chk_programmes_4 CHECK (end_date >= start_date),
    CONSTRAINT chk_programmes_5 CHECK (snatch_goal > 0),
    CONSTRAINT chk_programmes_6 CHECK (cj_goal > 0),
    CONSTRAINT fk_programmes_1 FOREIGN KEY (evaluation_id) REFERENCES eval_summaries (evaluation_id)
);

COMMENT ON TABLE programmes IS 'Programme d entraînement généré pour un athlète';
COMMENT ON COLUMN programmes.weeks IS 'Nombre de semaines du programme: 8, 12, 16';
COMMENT ON COLUMN programmes.frequency IS 'Nombre de séances par semaine: 3, 4, 5';
COMMENT ON COLUMN programmes.duration IS 'Durée d''une séance en minutes : 90, 120, 150';
COMMENT ON COLUMN programmes.start_date IS 'Date de début du programme';
COMMENT ON COLUMN programmes.end_date IS 'Date de fin du programme';
COMMENT ON COLUMN programmes.snatch_goal IS 'Objectif arraché en kg';
COMMENT ON COLUMN programmes.cj_goal IS 'Objectif épaulé-jeté en kg';

CREATE INDEX IF NOT EXISTS idx_programmes_1 ON programmes (evaluation_id);

-- ------------------------------------------------------------
-- PROG_WEEK
-- Semaine d entraînement dans un programme
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS programme_weeks
(
    programme_week_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    programme_id      INTEGER NOT NULL,
    week_number       INTEGER NOT NULL,
    start_date        DATE NOT NULL,
    end_date          DATE NOT NULL,
    week_type         VARCHAR(50) NOT NULL,
    base_percent      NUMERIC(1,2) NOT NULL,
    snatch_goal       INTEGER NOT NULL,
    cj_goal           INTEGER NOT NULL,
    back_squat_goal   INTEGER NOT NULL,
    front_squat_goal  INTEGER NOT NULL,
    snatch_pull_goal  INTEGER NOT NULL,
    cj_pull_goal      INTEGER NOT NULL,
    CONSTRAINT pk_programme_weeks PRIMARY KEY (programme_week_id),
    CONSTRAINT uq_programme_weeks_1 UNIQUE (programme_id, week_number),
    CONSTRAINT chk_programme_weeks_1 CHECK (week_number BETWEEN 1 AND 16),
    CONSTRAINT chk_programme_weeks_2 CHECK (base_percent > 0),
    CONSTRAINT chk_programme_weeks_3 CHECK (end_date >= start_date),
    CONSTRAINT chk_programme_weeks_4 CHECK (week_type IN ('VOLUME', 'TECH', 'STRENGTH', 'PEAK', 'DELOAD')),
    CONSTRAINT fk_programme_weeks_1 FOREIGN KEY (programme_id) REFERENCES programmes (programme_id)
);

COMMENT ON TABLE programme_weeks IS 'Découpage hebdomadaire d''un programme';
COMMENT ON COLUMN programme_weeks.week_type IS 'Type de semaine : VOLUME (F), TECH (T), STRENGTH (S), PEAK (A), DELOAD (D)';
COMMENT ON COLUMN programme_weeks.base_percent IS 'Pourcentage de l''objectif final';
COMMENT ON COLUMN programme_weeks.snatch_goal IS 'Base pour l''arraché';
COMMENT ON COLUMN programme_weeks.cj_goal IS 'Base pour l''épaulé-jeté';
COMMENT ON COLUMN programme_weeks.back_squat_goal IS 'Base pour le squat nuque';
COMMENT ON COLUMN programme_weeks.front_squat_goal IS 'Base pour les squat clavicule';
COMMENT ON COLUMN programme_weeks.snatch_pull_goal IS 'Base pour les tirages d''arraché';
COMMENT ON COLUMN programme_weeks.cj_pull_goal IS 'Base pour les tirages d''épaulé';

CREATE INDEX IF NOT EXISTS idx_programme_weeks_1 ON programme_weeks (programme_id);

-- ------------------------------------------------------------
-- PROG_TRAINING
-- Exercice planifié dans une séance hebdomadaire
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS programme_trainings
(
    programme_training_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    programme_week_id     INTEGER NOT NULL,
    training_number       INTEGER NOT NULL,
    exercice_order        INTEGER NOT NULL,
    exercice_code         VARCHAR(50) NOT NULL,
    set_number            INTEGER NOT NULL,
    rep_number            INTEGER NOT NULL,
    rep_label             VARCHAR(20),
    min_weight            NUMERIC(6, 2),
    max_weight            NUMERIC(6, 2),
    CONSTRAINT pk_programme_trainings PRIMARY KEY (programme_training_id),
    CONSTRAINT chk_programme_trainings_1 CHECK (exercice_order > 0),
    CONSTRAINT chk_programme_trainings_2 CHECK (set_number > 0),
    CONSTRAINT chk_programme_trainings_3 CHECK (rep_number > 0),
    CONSTRAINT chk_programme_trainings_4 CHECK (max_weight IS NULL OR max_weight >= min_weight),
    CONSTRAINT chk_programme_trainings_5 CHECK (training_number BETWEEN 1 AND 5),
    CONSTRAINT fk_programme_trainings_1 FOREIGN KEY (programme_week_id) REFERENCES programme_weeks (programme_week_id)
);

COMMENT ON TABLE programme_trainings IS 'Exercices planifiés dans une semaine de programme';
COMMENT ON COLUMN programme_trainings.training_number IS 'Numéro de la séance hebdomadaire';
COMMENT ON COLUMN programme_trainings.exercice_order IS 'Ordre de l''exercice dans la séance (si plusieurs fois le même ordre => "Au choix")';
COMMENT ON COLUMN programme_trainings.exercice_code IS 'Code unique identifiant l''exercice (voir libellé dans les fichiers i18n)';
COMMENT ON COLUMN programme_trainings.set_number IS 'Nombre de séries';
COMMENT ON COLUMN programme_trainings.rep_number IS 'Nombre de répétitions par série';
COMMENT ON COLUMN programme_trainings.rep_label IS 'Label des répétitions (si complexe, ex : "30s + 10 reps")';
COMMENT ON COLUMN programme_trainings.min_weight IS 'Charge minimale en kg';
COMMENT ON COLUMN programme_trainings.max_weight IS 'Charge maximale en kg';

CREATE INDEX IF NOT EXISTS idx_programme_trainings_1 ON programme_trainings (programme_week_id);

-- ------------------------------------------------------------
