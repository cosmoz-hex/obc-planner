COMMENT ON COLUMN ref_plannings.exercice_order IS 'Ordre de passage dans la séance, si plusieurs => "Au choix"';
COMMENT ON COLUMN ref_plannings.categorie_exercice IS 'Catégorie d''exercice attendue';
COMMENT ON COLUMN ref_plannings.type_exercice IS 'Type d''exercice attendu';
COMMENT ON COLUMN ref_plannings.strength_weakness IS 'STRENGTH = point fort, WEAKNESS = point faible';
COMMENT ON COLUMN ref_plannings.set_number IS 'Nombre de séries de référence';
COMMENT ON COLUMN ref_plannings.rep_number IS 'Nombre de répétitions de référence';
COMMENT ON COLUMN ref_plannings.rep_label IS 'Label des répétitions de référence';

CREATE INDEX IF NOT EXISTS idx_ref_plannings_1 ON ref_plannings (ref_timeline_id);
CREATE INDEX IF NOT EXISTS idx_ref_plannings_2 ON ref_plannings (week_type);