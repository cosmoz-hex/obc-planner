-- ============================================================
-- LOT 3 — Renforcement Spécifique (cases RF) : données par défaut
--
-- Spec : .kiro/specs/renforcement-specifique/ (US2, RG1/RG2/RG3/RG4/RG11).
--
-- Seed des protocoles de Renforcement Spécifique dans ref_exercices +
-- ref_exercice_sets, consommés par le moteur de génération (rotation RF) :
--   Arraché -> exercice_type RF, reference SN (3 goals : SN_CATCH/SN_EXT/SN_PATH)
--   Épaulé  -> exercice_type RF, reference CJ (3 goals : CL_CATCH/CL_PATH/CL_EXT)
--   Jeté    -> exercice_type RF, reference CJ (3 goals : JK_PATH/JK_EXT/JK_CATCH)
--
-- Règles appliquées :
--   RG3  week_type conventionnel : 'F' pour toutes les lignes RF (pas de
--        duplication sur F/T/S/A/D ; le moteur filtre RF sur exercice_type + goal).
--   RG2  goal composé {mouvement}_{objectif} parmi les 9 codes du CHECK étendu
--        (LOT 1 : V20261021_140000__renfo_specifique_schema.sql).
--   RG4  reference = SN (renfo arraché) / CJ (renfo épaulé et jeté) ;
--        weight = pourcentage du mouvement de référence.
--   RG11 rep_number textuel VARCHAR (ex. '5', '4', '6', '(4/4)').
--   training_order = rang de l'exercice dans son goal (1, 2, 3...).
--   Séries identiques pour les 5 archétypes (MID, CYCLE, ROUGH, TECH, LEARN).
--
-- Volume généré : 21 ref_exercices (Arraché 8, Épaulé 7, Jeté 6),
--   21 x 5 = 105 ref_exercice_sets.
--
-- Idempotent : ids GENERATED BY DEFAULT AS IDENTITY (non forcés) ; purge ciblée
-- (DELETE sets puis exercices sur exercice_type='RF') avant ré-insertion,
-- donc rejouable sans doublon. ⚠️ La purge retire aussi d'éventuelles lignes
-- RF saisies manuellement.
--
-- weight toujours renseigné (aucune branche 100 % NULL) -> pas de NULL::numeric
-- (cf. learning.md 2026-11-07).
--
-- Rollback : back-end/src/main/resources/db/rollback/V20261021_150000__renfo_specifique_data.sql
-- ============================================================


-- ------------------------------------------------------------
-- Purge idempotente (dépendances : sets avant exercices).
-- ------------------------------------------------------------
DELETE FROM ref_exercice_sets
 WHERE ref_exercice_id IN (
     SELECT ref_exercice_id FROM ref_exercices
      WHERE exercice_type = 'RF'
 );

DELETE FROM ref_exercices
 WHERE exercice_type = 'RF';


