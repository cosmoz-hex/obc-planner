-- ============================================================
-- LOT 1 — Refonte du modèle Programme en 3 niveaux (Séance -> Exercice -> Série)
--
-- Spec : .kiro/specs/refonte-modele-programme-series/ (US1, US2).
--
-- Objet :
--   Découper la table monolithique programme_trainings (un enregistrement par SÉRIE)
--   en une hiérarchie à 3 niveaux :
--     programme_trainings (SÉANCE)
--       -> programme_exercices (EXERCICE)
--            -> programme_series (SÉRIE)
--
--   1. Vidage des tables de génération (ordre des FK) — programmes régénérables (RG9).
--   2. Recentrage de programme_trainings sur la SÉANCE (retrait des colonnes
--      exercice/série + CHECK associés).
--   3. Création de programme_exercices (EXERCICE).
--   4. Création de programme_series (SÉRIE), rep_number VARCHAR(50) (absorbe l'ex
--      rep_label combiné Épaulé-Jeté, cf. learning.md 2026-11-08).
--
-- Idempotent : DROP ... IF EXISTS, CREATE ... IF NOT EXISTS, ALTER ... IF EXISTS,
-- blocs DO $$ conditionnels sur information_schema pour les contraintes/colonnes.
-- Destructif (données) : les tables programme* sont exclusivement alimentées par le
-- moteur de génération ; leur vidage est assumé (RG9). Aucune restauration de données
-- dans le rollback (db/rollback/V20261021_100000__refonte_modele_programme_series.sql).
-- ============================================================


-- ------------------------------------------------------------
-- 1 — Vidage des données (respect de l'ordre des FK)
-- programme_trainings -> programme_weeks -> programmes
-- (les nouvelles tables n'existent pas encore ; programme_trainings est vidée
--  avant d'être recentrée sur la séance.)
-- ------------------------------------------------------------
DELETE FROM programme_trainings;
DELETE FROM programme_weeks;
DELETE FROM programmes;


-- ------------------------------------------------------------
-- 2 — Recentrer programme_trainings sur la SÉANCE
-- Retrait des CHECK liés aux colonnes exercice/série puis des colonnes elles-mêmes.
-- Conservés : programme_training_id (PK), programme_week_id (FK CASCADE),
--             training_number (chk_programme_trainings_5 BETWEEN 1 AND 5),
--             idx_programme_trainings_1, fk_programme_trainings_1.
-- ------------------------------------------------------------
ALTER TABLE programme_trainings DROP CONSTRAINT IF EXISTS chk_programme_trainings_1; -- exercice_order > 0
ALTER TABLE programme_trainings DROP CONSTRAINT IF EXISTS chk_programme_trainings_2; -- set_number (NULL OR > 0)
ALTER TABLE programme_trainings DROP CONSTRAINT IF EXISTS chk_programme_trainings_3; -- rep_number > 0 (déjà retiré en V20261020_100000)
ALTER TABLE programme_trainings DROP CONSTRAINT IF EXISTS chk_programme_trainings_4; -- max_weight >= min_weight

ALTER TABLE programme_trainings DROP COLUMN IF EXISTS exercice_order;
ALTER TABLE programme_trainings DROP COLUMN IF EXISTS exercice_name;
ALTER TABLE programme_trainings DROP COLUMN IF EXISTS set_number;
ALTER TABLE programme_trainings DROP COLUMN IF EXISTS rep_number;
ALTER TABLE programme_trainings DROP COLUMN IF EXISTS rep_label;
ALTER TABLE programme_trainings DROP COLUMN IF EXISTS min_weight;
ALTER TABLE programme_trainings DROP COLUMN IF EXISTS max_weight;

COMMENT ON TABLE programme_trainings IS 'Séance planifiée d''une semaine de programme';


-- ------------------------------------------------------------
-- 3 — programme_exercices (EXERCICE)
-- Un exercice planifié dans une séance (exercice_order = position ; plusieurs
-- exercices au même ordre = alternatives "Au choix").
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS programme_exercices
(
    programme_exercice_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    programme_training_id INTEGER       NOT NULL,
    exercice_order        INTEGER       NOT NULL,
    exercice_name         VARCHAR(255)  NOT NULL,
    CONSTRAINT pk_programme_exercices PRIMARY KEY (programme_exercice_id),
    CONSTRAINT chk_programme_exercices_1 CHECK (exercice_order > 0),
    CONSTRAINT fk_programme_exercices_1 FOREIGN KEY (programme_training_id)
        REFERENCES programme_trainings (programme_training_id) ON DELETE CASCADE
);

COMMENT ON TABLE programme_exercices IS 'Exercice planifié dans une séance de programme (position + nom ; même ordre = "Au choix")';
COMMENT ON COLUMN programme_exercices.programme_exercice_id IS 'Identifiant auto-généré';
COMMENT ON COLUMN programme_exercices.programme_training_id IS 'Séance parente (FK -> programme_trainings)';
COMMENT ON COLUMN programme_exercices.exercice_order IS 'Ordre de l''exercice dans la séance (si plusieurs fois le même ordre => "Au choix")';
COMMENT ON COLUMN programme_exercices.exercice_name IS 'Nom de l''exercice planifié (libellé libre, non lié au catalogue)';

CREATE INDEX IF NOT EXISTS idx_programme_exercices_1 ON programme_exercices (programme_training_id);


-- ------------------------------------------------------------
-- 4 — programme_series (SÉRIE)
-- Une série d'un exercice planifié. rep_number VARCHAR(50) : aligné sur
-- ref_exercice_sets.rep_number (VARCHAR(20)) mais élargi à 50 pour absorber le
-- libellé combiné Épaulé-Jeté (ex-rep_label VARCHAR(50)), cf. learning.md 2026-11-08.
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS programme_series
(
    programme_series_id   INTEGER GENERATED BY DEFAULT AS IDENTITY,
    programme_exercice_id INTEGER       NOT NULL,
    set_number            INTEGER,
    rep_number            VARCHAR(50),
    min_weight            NUMERIC(6, 2),
    max_weight            NUMERIC(6, 2),
    CONSTRAINT pk_programme_series PRIMARY KEY (programme_series_id),
    CONSTRAINT chk_programme_series_1 CHECK (set_number IS NULL OR set_number > 0),
    CONSTRAINT chk_programme_series_2 CHECK (max_weight IS NULL OR max_weight >= min_weight),
    CONSTRAINT fk_programme_series_1 FOREIGN KEY (programme_exercice_id)
        REFERENCES programme_exercices (programme_exercice_id) ON DELETE CASCADE
);

COMMENT ON TABLE programme_series IS 'Série d''un exercice planifié (nombre de séries, répétitions, charges)';
COMMENT ON COLUMN programme_series.programme_series_id IS 'Identifiant auto-généré';
COMMENT ON COLUMN programme_series.programme_exercice_id IS 'Exercice parent (FK -> programme_exercices)';
COMMENT ON COLUMN programme_series.set_number IS 'Nombre de séries (NULL pour les cases sans série : RF, PC, "à définir")';
COMMENT ON COLUMN programme_series.rep_number IS 'Répétitions au format libre : 6, 30s, (1 + 1), libellé combiné Épaulé-Jeté, ou NULL';
COMMENT ON COLUMN programme_series.min_weight IS 'Charge minimale en kg';
COMMENT ON COLUMN programme_series.max_weight IS 'Charge maximale en kg';

CREATE INDEX IF NOT EXISTS idx_programme_series_1 ON programme_series (programme_exercice_id);
