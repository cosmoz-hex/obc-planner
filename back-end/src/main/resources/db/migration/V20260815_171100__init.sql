-- ------------------------------------------------------------
-- EXERCICE
-- Catalogue des exercices de référence
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS exercices
(
    exercice_id        INTEGER GENERATED BY DEFAULT AS IDENTITY,
    exercice_ref       INTEGER,
    type_exercice      VARCHAR(10) NOT NULL,
    categorie_exercice VARCHAR(10) NOT NULL,
    exercice_code      VARCHAR(50) NOT NULL,
    estimate_value     NUMERIC(4, 2),
    CONSTRAINT pk_exercices PRIMARY KEY (exercice_id),
    CONSTRAINT uq_exercices_1 UNIQUE (exercice_code),
    CONSTRAINT fk_exercices_1 FOREIGN KEY (exercice_ref) REFERENCES exercices (exercice_id),
    CONSTRAINT chk_exercices_1 CHECK (type_exercice IN ('SQUAT', 'PULL', 'SNATCH', 'CLEAN', 'JERK')),
    CONSTRAINT chk_exercices_2 CHECK (categorie_exercice IN ('TECH', 'COMBI', 'SEMI_LEGER', 'SEMI_LOURD', 'RENFO', 'CARDIO', 'PLYO', 'BACK', 'FRONT'))
);

COMMENT ON TABLE exercices IS 'Catalogue des exercices de référence';
COMMENT ON COLUMN exercices.exercice_ref IS 'Référence vers un exercice parent (auto-référence)';
COMMENT ON COLUMN exercices.type_exercice IS 'Type d''exercice : SQUAT, PULL, SNATCH, CLEAN, JERK, MUSCU';
COMMENT ON COLUMN exercices.categorie_exercice IS 'Catégorie d''exercice ou groupe musculaire : TECH, COMBI, SEMI_LEGER, SEMI_LOURD, RENFO, GEN, LEG, POST, CORE, CARDIO, PLYO';
COMMENT ON COLUMN exercices.exercice_code IS 'Code unique identifiant l exercice (voir libellé dans les fichiers i18n)';
COMMENT ON COLUMN exercices.estimate_value IS 'Charge théorique (% de l''exercice de référence)';

-- ------------------------------------------------------------
-- CORRECTION
-- Table de liaison exercice → exercices correctifs
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS corrections
(
    exercice_id   INTEGER NOT NULL,
    correction_id INTEGER NOT NULL,
    CONSTRAINT pk_corrections PRIMARY KEY (exercice_id, correction_id),
    CONSTRAINT fk_corrections_1 FOREIGN KEY (exercice_id) REFERENCES exercices (exercice_id),
    CONSTRAINT fk_corrections_2 FOREIGN KEY (correction_id) REFERENCES exercices (exercice_id)
);

COMMENT ON TABLE corrections IS 'Exercices correctifs associés à un exercice principal';

