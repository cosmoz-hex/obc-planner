-- ============================================================
-- LOT 1 — Refonte de la préparation à la génération de programme
--
-- ⚠️ MIGRATION DESTRUCTIVE : vidage de eval_summaries (et dépendances),
-- suppression de colonnes, DROP de tables de référence devenues inutiles.
-- Des données existantes seront définitivement perdues (évaluations,
-- programmes, exercices de référence, correctifs, trames de référence).
--
-- Idempotent : DELETE (sans effet si vide), DROP ... IF EXISTS,
-- ADD COLUMN IF NOT EXISTS, DROP COLUMN IF EXISTS, CREATE TABLE IF NOT EXISTS,
-- blocs DO $$ conditionnels pour les RENAME COLUMN.
-- ============================================================


-- ------------------------------------------------------------
-- US3 — Vidage de eval_summaries et des données dépendantes
-- Ordre : enfants d'abord pour respecter les FK
-- (programme_trainings -> programme_weeks -> programmes -> eval_summaries,
--  eval_details -> eval_summaries)
-- ------------------------------------------------------------
DELETE FROM programme_trainings;
DELETE FROM programme_weeks;
DELETE FROM programmes;
DELETE FROM eval_details;
DELETE FROM eval_summaries;


-- ------------------------------------------------------------
-- US3 — eval_summaries : suppression des points forts techniques
-- ------------------------------------------------------------
ALTER TABLE eval_summaries DROP COLUMN IF EXISTS snatch_strength;
ALTER TABLE eval_summaries DROP COLUMN IF EXISTS clean_strength;
ALTER TABLE eval_summaries DROP COLUMN IF EXISTS jerk_strength;

-- ------------------------------------------------------------
-- US3 — eval_summaries : renommage des points faibles techniques
-- snatch_weakness -> snatch, clean_weakness -> clean, jerk_weakness -> jerk
-- Blocs conditionnels pour l'idempotence (RENAME non rejouable nativement).
-- ------------------------------------------------------------
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM information_schema.columns
               WHERE table_name = 'eval_summaries' AND column_name = 'snatch_weakness') THEN
        ALTER TABLE eval_summaries RENAME COLUMN snatch_weakness TO snatch;
    END IF;
END $$;

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM information_schema.columns
               WHERE table_name = 'eval_summaries' AND column_name = 'clean_weakness') THEN
        ALTER TABLE eval_summaries RENAME COLUMN clean_weakness TO clean;
    END IF;
END $$;

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM information_schema.columns
               WHERE table_name = 'eval_summaries' AND column_name = 'jerk_weakness') THEN
        ALTER TABLE eval_summaries RENAME COLUMN jerk_weakness TO jerk;
    END IF;
END $$;

COMMENT ON COLUMN eval_summaries.snatch IS 'Point faible technique à l''arraché : EXT, CATCH, PATH';
COMMENT ON COLUMN eval_summaries.clean IS 'Point faible technique à l''épaulé : EXT, CATCH, PATH';
COMMENT ON COLUMN eval_summaries.jerk IS 'Point faible technique au jeté : EXT, CATCH, PATH';


-- ------------------------------------------------------------
-- US2 — programme_trainings : exercice_code -> exercice_name VARCHAR(100)
-- La table est vidée ci-dessus, exercice_name peut être créée NOT NULL.
-- ------------------------------------------------------------
ALTER TABLE programme_trainings DROP COLUMN IF EXISTS exercice_code;
ALTER TABLE programme_trainings ADD COLUMN IF NOT EXISTS exercice_name VARCHAR(100) NOT NULL;

COMMENT ON COLUMN programme_trainings.exercice_name IS 'Nom de l''exercice planifié (libellé libre, non lié au catalogue)';


-- ------------------------------------------------------------
-- US1 — Suppression des tables de référence obsolètes
-- Ordre : dépendants d'abord (corrections -> exercices).
-- ------------------------------------------------------------
DROP TABLE IF EXISTS corrections;
DROP TABLE IF EXISTS exercices;
DROP TABLE IF EXISTS ref_squats;
DROP TABLE IF EXISTS ref_pulls;
DROP TABLE IF EXISTS ref_plannings;


-- ------------------------------------------------------------
-- US4 — Recréation de ref_plannings (nouvelle structure, sans FK)
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS ref_plannings
(
    ref_planning_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    weeks_numbers   INTEGER     NOT NULL,
    training_order  INTEGER     NOT NULL,
    exercice_order  INTEGER     NOT NULL,
    exercice_type   VARCHAR(10) NOT NULL,
    CONSTRAINT pk_ref_plannings PRIMARY KEY (ref_planning_id),
    CONSTRAINT chk_ref_plannings_1 CHECK (weeks_numbers IN (3, 4, 5)),
    CONSTRAINT chk_ref_plannings_2 CHECK (training_order BETWEEN 1 AND 5),
    CONSTRAINT chk_ref_plannings_3 CHECK (exercice_order BETWEEN 1 AND 6),
    CONSTRAINT chk_ref_plannings_4 CHECK (exercice_type IN ('SN', 'CJ', 'SQ', 'PL', 'RF', 'MS'))
);

COMMENT ON TABLE ref_plannings IS 'Planning de référence du moteur de génération (séances type par nombre de séances hebdomadaires)';
COMMENT ON COLUMN ref_plannings.weeks_numbers IS 'Nombre de séances par semaine : 3, 4, 5';
COMMENT ON COLUMN ref_plannings.training_order IS 'Numéro de la séance dans la semaine (1 à 5)';
COMMENT ON COLUMN ref_plannings.exercice_order IS 'Ordre de l''exercice dans la séance (même ordre = "Au choix")';
COMMENT ON COLUMN ref_plannings.exercice_type IS 'Type d''exercice attendu : SN, CJ, SQ, PL, RF, MS';


-- ------------------------------------------------------------
-- US5 — Création de ref_exercices (sans FK)
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS ref_exercices
(
    ref_exercice_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    exercice_type   VARCHAR(10)  NOT NULL,
    week_type       VARCHAR(10)  NOT NULL,
    goal            VARCHAR(10)  NOT NULL,
    training_order  INTEGER      NOT NULL,
    exercice_name   VARCHAR(100) NOT NULL,
    reference       VARCHAR(10)  NOT NULL,
    CONSTRAINT pk_ref_exercices PRIMARY KEY (ref_exercice_id),
    CONSTRAINT chk_ref_exercices_1 CHECK (exercice_type IN ('SN', 'CJ', 'SQ', 'PL', 'RF', 'MS')),
    CONSTRAINT chk_ref_exercices_2 CHECK (week_type IN ('F', 'T', 'S', 'A', 'D')),
    CONSTRAINT chk_ref_exercices_3 CHECK (goal IN ('EXT', 'CATCH', 'PATH', 'KEEP', 'STR', 'SPD')),
    CONSTRAINT chk_ref_exercices_4 CHECK (training_order > 0),
    CONSTRAINT chk_ref_exercices_5 CHECK (reference IN ('SN', 'CJ', 'FS', 'BS', 'SP', 'CP'))
);

COMMENT ON TABLE ref_exercices IS 'Catalogue de référence des exercices du moteur de génération';
COMMENT ON COLUMN ref_exercices.exercice_type IS 'Type d''exercice : SN, CJ, SQ, PL, RF, MS';
COMMENT ON COLUMN ref_exercices.week_type IS 'Type de semaine : F (Volume), T (Tech), S (Strength), A (Peak), D (Deload)';
COMMENT ON COLUMN ref_exercices.goal IS 'Objectif : EXT, CATCH, PATH, KEEP, STR, SPD';
COMMENT ON COLUMN ref_exercices.training_order IS 'Ordre de l''exercice dans la séance';
COMMENT ON COLUMN ref_exercices.exercice_name IS 'Nom de l''exercice de référence';
COMMENT ON COLUMN ref_exercices.reference IS 'Exercice de référence pour le calcul de charge : SN, CJ, FS, BS, SP, CP';


-- ------------------------------------------------------------
-- US6 — Création de ref_exercice_sets (FK vers ref_exercices)
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS ref_exercice_sets
(
    ref_exercice_set_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    ref_exercice_id     INTEGER     NOT NULL,
    archetype           VARCHAR(10) NOT NULL,
    set_number          INTEGER     NOT NULL,
    rep_number          INTEGER     NOT NULL,
    weight              NUMERIC(6, 2),
    CONSTRAINT pk_ref_exercice_sets PRIMARY KEY (ref_exercice_set_id),
    CONSTRAINT fk_ref_exercice_sets_1 FOREIGN KEY (ref_exercice_id) REFERENCES ref_exercices (ref_exercice_id),
    CONSTRAINT chk_ref_exercice_sets_1 CHECK (archetype IN ('MID', 'ROUGH', 'TECH', 'CYCLE', 'LEARN')),
    CONSTRAINT chk_ref_exercice_sets_2 CHECK (set_number > 0),
    CONSTRAINT chk_ref_exercice_sets_3 CHECK (rep_number > 0)
);

COMMENT ON TABLE ref_exercice_sets IS 'Séries/répétitions de référence par exercice et archétype';
COMMENT ON COLUMN ref_exercice_sets.ref_exercice_id IS 'Exercice de référence parent';
COMMENT ON COLUMN ref_exercice_sets.archetype IS 'Archétype de l''athlète : MID, ROUGH, TECH, CYCLE, LEARN';
COMMENT ON COLUMN ref_exercice_sets.set_number IS 'Nombre de séries de référence';
COMMENT ON COLUMN ref_exercice_sets.rep_number IS 'Nombre de répétitions de référence';
COMMENT ON COLUMN ref_exercice_sets.weight IS 'Charge de référence en kg (ou % selon usage du moteur)';

CREATE INDEX IF NOT EXISTS idx_ref_exercice_sets_1 ON ref_exercice_sets (ref_exercice_id);
